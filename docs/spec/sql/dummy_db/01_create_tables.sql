CREATE TABLE APP_MEMBER (
    MEMBER_ID              NUMBER(19)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    MEMBER_CODE            VARCHAR2(20 CHAR)    NOT NULL,
    EMAIL                  VARCHAR2(100 CHAR)   NOT NULL,
    PASSWORD_HASH          VARCHAR2(100 CHAR),
    NICKNAME               VARCHAR2(30 CHAR)    NOT NULL,
    BIRTH_YEAR             NUMBER(4)            NOT NULL,
    JOB_TYPE_CODE          VARCHAR2(20 CHAR)    NOT NULL,
    ROLE_CODE              VARCHAR2(20 CHAR)    DEFAULT 'ROLE_USER' NOT NULL,
    EXTERNAL_CONSENT_YN    CHAR(1)              DEFAULT 'N' NOT NULL,
    SIGNUP_DATE            DATE                 NOT NULL,
    DUMMY_YN               CHAR(1)              DEFAULT 'N' NOT NULL,
    CREATED_AT             TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP,
    CONSTRAINT PK_APP_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_MBR_1 UNIQUE (MEMBER_CODE),
    CONSTRAINT UK_MBR_2 UNIQUE (EMAIL),
    CONSTRAINT CK_MBR_BIRTH_YEAR CHECK (BIRTH_YEAR BETWEEN 1900 AND 2026),
    CONSTRAINT CK_MBR_JOB_TYPE_CODE CHECK (JOB_TYPE_CODE IN ('EMPLOYEE', 'SELF_EMPLOYED', 'FREELANCER')),
    CONSTRAINT CK_MBR_ROLE_CODE CHECK (ROLE_CODE IN ('ROLE_USER', 'ROLE_ADMIN')),
    CONSTRAINT CK_MBR_EXTERNAL_CONSENT_YN CHECK (EXTERNAL_CONSENT_YN IN ('Y', 'N')),
    CONSTRAINT CK_MBR_DUMMY_YN CHECK (DUMMY_YN IN ('Y', 'N'))
);
COMMENT ON TABLE  APP_MEMBER IS '회원 기본 정보 (더미 회원 400명 포함)';
COMMENT ON COLUMN APP_MEMBER.MEMBER_ID IS '회원 ID (PK, 자동 증가)';
COMMENT ON COLUMN APP_MEMBER.MEMBER_CODE IS '회원 코드 (더미는 MEM+6자리, 외부 API 응답·원장과 연결하는 키)';
COMMENT ON COLUMN APP_MEMBER.EMAIL IS '로그인 이메일 (더미는 example.com)';
COMMENT ON COLUMN APP_MEMBER.PASSWORD_HASH IS 'BCrypt 해시 비밀번호 (더미 회원은 NULL)';
COMMENT ON COLUMN APP_MEMBER.NICKNAME IS '닉네임';
COMMENT ON COLUMN APP_MEMBER.BIRTH_YEAR IS '출생연도 (연령대는 이 값으로 계산)';
COMMENT ON COLUMN APP_MEMBER.JOB_TYPE_CODE IS '직군 코드 (EMPLOYEE=급여소득자, SELF_EMPLOYED=자영업자, FREELANCER=프리랜서)';
