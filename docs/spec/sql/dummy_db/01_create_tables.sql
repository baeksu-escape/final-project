    CONSTRAINT CK_LPRD_RATE_MIN_PCT CHECK (RATE_MIN_PCT BETWEEN 0 AND 20),
    CONSTRAINT CK_LPRD_RATE_MAX_PCT CHECK (RATE_MAX_PCT BETWEEN 0 AND 20),
    CONSTRAINT CK_LPRD_RATE_ANCHOR_PCT CHECK (RATE_ANCHOR_PCT BETWEEN 0 AND 20),
    CONSTRAINT CK_LPRD_RATE_ANCHOR_BASIS CHECK (RATE_ANCHOR_BASIS IN ('statistic', 'assumption')),
    CONSTRAINT CK_LPRD_RATE_ANCHOR_MONTH CHECK (REGEXP_LIKE(RATE_ANCHOR_MONTH, '^\d{4}-(0[1-9]|1[0-2])$')),
    CONSTRAINT CK_LPRD_LIMIT_MIN_AMT CHECK (LIMIT_MIN_AMT >= 0),
    CONSTRAINT CK_LPRD_LIMIT_MAX_AMT CHECK (LIMIT_MAX_AMT >= 0),
    CONSTRAINT CK_LPRD_TERM_MIN_MONTHS CHECK (TERM_MIN_MONTHS >= 1),
    CONSTRAINT CK_LPRD_TERM_MAX_MONTHS CHECK (TERM_MAX_MONTHS >= 1),
    CONSTRAINT CK_LPRD_DUMMY_YN CHECK (DUMMY_YN IN ('Y', 'N')),
    CONSTRAINT CK_LPRD_RATE CHECK (RATE_MIN_PCT <= RATE_ANCHOR_PCT AND RATE_ANCHOR_PCT <= RATE_MAX_PCT),
    CONSTRAINT CK_LPRD_LIMIT CHECK (LIMIT_MIN_AMT <= LIMIT_MAX_AMT),
    CONSTRAINT CK_LPRD_TERM CHECK (TERM_MIN_MONTHS <= TERM_MAX_MONTHS)
