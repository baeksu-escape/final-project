-- N-15-2 동년배 기준값 조회 및 N-15-3 비교 분석용 공공통계 테이블 및 시드 데이터
-- 가계금융복지조사(HFS) 및 직군·연령별 소득 통계 (Oracle 21c)

-- 1. 가계금융복지조사 연령대별 통계 (FACT_HFS_STAT)
CREATE TABLE FACT_HFS_STAT (
    STAT_ID                NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    STAT_YEAR              NUMBER(4)            DEFAULT 2025 NOT NULL,
    AGE_GROUP              VARCHAR2(20 CHAR)    NOT NULL,
    AVG_ANNUAL_INCOME      NUMBER(15)           NOT NULL,
    AVG_TOTAL_ASSET        NUMBER(15)           NOT NULL,
    AVG_TOTAL_DEBT         NUMBER(15)           NOT NULL,
    SAMPLE_SIZE            NUMBER(10),
    CREATED_AT             DATE                 DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_FACT_HFS_STAT PRIMARY KEY (STAT_ID),
    CONSTRAINT UQ_FHS_YEAR_AGE UNIQUE (STAT_YEAR, AGE_GROUP),
    CONSTRAINT CK_FHS_AGE_GROUP CHECK (AGE_GROUP IN ('20대', '30대', '40대', '50대 이상')),
    CONSTRAINT CK_FHS_INCOME CHECK (AVG_ANNUAL_INCOME >= 0),
    CONSTRAINT CK_FHS_ASSET CHECK (AVG_TOTAL_ASSET >= 0),
    CONSTRAINT CK_FHS_DEBT CHECK (AVG_TOTAL_DEBT >= 0)
);

COMMENT ON TABLE FACT_HFS_STAT IS '가계금융복지조사 연령대별 평균 자산·부채·소득 통계 (N-15-2 동년배 기준값)';
COMMENT ON COLUMN FACT_HFS_STAT.STAT_ID IS '통계 식별자 (PK)';
COMMENT ON COLUMN FACT_HFS_STAT.STAT_YEAR IS '통계 기준 연도';
COMMENT ON COLUMN FACT_HFS_STAT.AGE_GROUP IS '연령 구간 (20대, 30대, 40대, 50대 이상)';
COMMENT ON COLUMN FACT_HFS_STAT.AVG_ANNUAL_INCOME IS '평균 연간 소득 (원 단위)';
COMMENT ON COLUMN FACT_HFS_STAT.AVG_TOTAL_ASSET IS '평균 총 자산 (원 단위)';
COMMENT ON COLUMN FACT_HFS_STAT.AVG_TOTAL_DEBT IS '평균 총 부채 (원 단위)';
COMMENT ON COLUMN FACT_HFS_STAT.SAMPLE_SIZE IS '표본 수 (가구 수)';
COMMENT ON COLUMN FACT_HFS_STAT.CREATED_AT IS '생성 일시';

-- 2. 직군·연령별 소득·자산·부채 통계 (FACT_INDUSTRY_AGE_INCOME)
CREATE TABLE FACT_INDUSTRY_AGE_INCOME (
    STAT_ID                NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    STAT_YEAR              NUMBER(4)            DEFAULT 2025 NOT NULL,
    JOB_TYPE               VARCHAR2(30 CHAR)    NOT NULL,
    AGE_GROUP              VARCHAR2(20 CHAR)    NOT NULL,
    AVG_ANNUAL_INCOME      NUMBER(15)           NOT NULL,
    AVG_TOTAL_ASSET        NUMBER(15)           NOT NULL,
    AVG_TOTAL_DEBT         NUMBER(15)           NOT NULL,
    CREATED_AT             DATE                 DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_FACT_INDUSTRY_AGE PRIMARY KEY (STAT_ID),
    CONSTRAINT UQ_FIAI_YEAR_JOB_AGE UNIQUE (STAT_YEAR, JOB_TYPE, AGE_GROUP),
    CONSTRAINT CK_FIAI_JOB_TYPE CHECK (JOB_TYPE IN ('EMPLOYEE', 'SELF_EMPLOYED', 'FREELANCER')),
    CONSTRAINT CK_FIAI_AGE_GROUP CHECK (AGE_GROUP IN ('20대', '30대', '40대', '50대 이상')),
    CONSTRAINT CK_FIAI_INCOME CHECK (AVG_ANNUAL_INCOME >= 0),
    CONSTRAINT CK_FIAI_ASSET CHECK (AVG_TOTAL_ASSET >= 0),
    CONSTRAINT CK_FIAI_DEBT CHECK (AVG_TOTAL_DEBT >= 0)
);

COMMENT ON TABLE FACT_INDUSTRY_AGE_INCOME IS '직군 및 연령대별 평균 소득·자산·부채 통계';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.STAT_ID IS '통계 식별자 (PK)';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.STAT_YEAR IS '통계 기준 연도';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.JOB_TYPE IS '직군 구분 (EMPLOYEE, SELF_EMPLOYED, FREELANCER)';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.AGE_GROUP IS '연령 구간 (20대, 30대, 40대, 50대 이상)';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.AVG_ANNUAL_INCOME IS '평균 연간 소득 (원 단위)';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.AVG_TOTAL_ASSET IS '평균 총 자산 (원 단위)';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.AVG_TOTAL_DEBT IS '평균 총 부채 (원 단위)';
COMMENT ON COLUMN FACT_INDUSTRY_AGE_INCOME.CREATED_AT IS '생성 일시';

