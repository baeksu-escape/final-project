-- 피처 세트 FS-V1(DRAFT)과 모델 버전 LGBM-BASE-0.1(CANDIDATE) 두 행을 이미 만들어진 DB에 추가한다.
-- 정의서 11장 모델 피처 38개 중 FEATURE_SET_VERSION·MODEL_REGISTRY 부분이다. DIM_FEATURE 38행은 이 파일 다음에
-- docs/spec/sql/seed/avenue_seed_dim_feature_fs_v1.sql을 한 번 실행해서 넣는다(FS-V1 행이 먼저 있어야 한다).
-- 새로 DDL을 실행하는 DB는 avenue_ddl.sql 기준 데이터에 이미 들어 있으므로 이 파일이 필요 없다.
-- 이미 같은 버전이 있으면 넣지 않으므로 다시 실행해도 된다. 서비스는 바뀌지 않는다: MODEL_REGISTRY의 ACTIVE는 그대로이며,
-- ACTIVE 전환(DEV-DUMMY를 RETIRED로, LGBM-BASE-0.1을 ACTIVE로)은 이 파일에 없고 activate_model_lgbm_base_0_1.sql이 따로 한다.
-- SQL*Plus/SQLcl/SQL Developer에서 대상 스키마 소유자로 실행한다.
WHENEVER SQLERROR EXIT SQL.SQLCODE
WHENEVER OSERROR EXIT FAILURE

MERGE INTO FEATURE_SET_VERSION t
USING (SELECT 'FS-V1' AS FEATURE_SET_VERSION,
              'DRAFT' AS STATUS_CODE,
              '피처 정의서 v1.0 11장 모델 피처 38개(LRZ021201 제외, C9). 임시 결정이 남은 DRAFT' AS NOTE
         FROM DUAL) s
   ON (t.FEATURE_SET_VERSION = s.FEATURE_SET_VERSION)
 WHEN NOT MATCHED THEN
      INSERT (FEATURE_SET_VERSION, STATUS_CODE, NOTE)
      VALUES (s.FEATURE_SET_VERSION, s.STATUS_CODE, s.NOTE);

MERGE INTO MODEL_REGISTRY t
USING (SELECT 'LGBM-BASE-0.1' AS MODEL_VERSION,
              'LightGBM' AS ALGORITHM_NAME,
              'FS-V1' AS FEATURE_SET_VERSION,
              'CANDIDATE' AS STATUS_CODE,
              TIMESTAMP '2026-11-16 11:19:49' AS TRAINED_AT,
              'LightGBM 임시 베이스라인 0.1(합성 데이터, 튜닝 없음). 학습 시각은 UTC. 재학습하면 0.2, 0.3으로 올린다' AS NOTE
         FROM DUAL) s
   ON (t.MODEL_VERSION = s.MODEL_VERSION)
 WHEN NOT MATCHED THEN
      INSERT (MODEL_VERSION, ALGORITHM_NAME, FEATURE_SET_VERSION, STATUS_CODE, TRAINED_AT, NOTE)
      VALUES (s.MODEL_VERSION, s.ALGORITHM_NAME, s.FEATURE_SET_VERSION, s.STATUS_CODE, s.TRAINED_AT, s.NOTE);

COMMIT;

-- 확인: FS-V1 DRAFT 1행, LGBM-BASE-0.1 CANDIDATE 1행이 나오고 ACTIVE 모델은 그대로(예: DEV-DUMMY) 있어야 한다.
SELECT FEATURE_SET_VERSION, STATUS_CODE FROM FEATURE_SET_VERSION ORDER BY FEATURE_SET_VERSION;
SELECT MODEL_VERSION, FEATURE_SET_VERSION, STATUS_CODE FROM MODEL_REGISTRY ORDER BY MODEL_VERSION;
