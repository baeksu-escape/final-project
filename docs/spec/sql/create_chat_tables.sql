-- N-07 FP-287 기존 DB에 1:1 문의 채팅 표 2개(CHAT_ROOM, CHAT_MESSAGE)만 추가한다(DDL C19). APP_USER가 있는 스키마에서 한 번 실행한다.
-- Oracle DDL은 자동 COMMIT된다. 기존 테이블이 있으면 오류로 중단하며 데이터는 추가하지 않는다.
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
-- v0.3.2 (C19) N-07 1:1 채팅. 회원마다 방 하나, 관리자는 누구나 답장한다.
CREATE TABLE CHAT_ROOM (
    ROOM_ID                    NUMBER(19)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID                    NUMBER(19)   NOT NULL,
    USER_LAST_READ_MESSAGE_ID  NUMBER(19)   DEFAULT 0 NOT NULL,
    ADMIN_LAST_READ_MESSAGE_ID NUMBER(19)   DEFAULT 0 NOT NULL,
    LAST_MESSAGE_AT            TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_AT                 TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CHAT_ROOM PRIMARY KEY (ROOM_ID),
    CONSTRAINT UQ_CHR_USER UNIQUE (USER_ID),
    CONSTRAINT FK_CHR_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID)
);
COMMENT ON TABLE  CHAT_ROOM IS 'v0.3.2 (C19) 회원의 1:1 문의 채팅방 (N-07). 회원당 하나';
COMMENT ON COLUMN CHAT_ROOM.ROOM_ID IS '채팅방 번호';
COMMENT ON COLUMN CHAT_ROOM.USER_ID IS '문의한 회원';
COMMENT ON COLUMN CHAT_ROOM.USER_LAST_READ_MESSAGE_ID IS '회원이 읽은 마지막 메시지 번호 (0 = 읽은 것 없음)';
COMMENT ON COLUMN CHAT_ROOM.ADMIN_LAST_READ_MESSAGE_ID IS '관리자가 읽은 마지막 메시지 번호. 관리자끼리 함께 쓴다 (0 = 읽은 것 없음)';
COMMENT ON COLUMN CHAT_ROOM.LAST_MESSAGE_AT IS '마지막 메시지 시각. 관리자 문의 목록을 최근 순으로 보여 준다';
COMMENT ON COLUMN CHAT_ROOM.CREATED_AT IS '첫 문의 시각';

CREATE TABLE CHAT_MESSAGE (
    MESSAGE_ID             NUMBER(19)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ROOM_ID                NUMBER(19)           NOT NULL,
    SENDER_USER_ID         NUMBER(19)           NOT NULL,
    SENDER_TYPE_CODE       VARCHAR2(10 CHAR)    NOT NULL,
    CONTENT                VARCHAR2(500 CHAR)   NOT NULL,
    CREATED_AT             TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CHAT_MESSAGE PRIMARY KEY (MESSAGE_ID),
    CONSTRAINT FK_CHM_ROOM FOREIGN KEY (ROOM_ID) REFERENCES CHAT_ROOM (ROOM_ID),
    CONSTRAINT FK_CHM_SENDER FOREIGN KEY (SENDER_USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_CHM_SENDER_TYPE CHECK (SENDER_TYPE_CODE IN ('USER', 'ADMIN'))
);
COMMENT ON TABLE  CHAT_MESSAGE IS 'v0.3.2 (C19) 1:1 문의 채팅 메시지 (N-07). 수정·삭제 기능 없음';
COMMENT ON COLUMN CHAT_MESSAGE.MESSAGE_ID IS '메시지 번호. 같은 방에서는 저장 순서대로 커진다';
COMMENT ON COLUMN CHAT_MESSAGE.ROOM_ID IS '채팅방';
COMMENT ON COLUMN CHAT_MESSAGE.SENDER_USER_ID IS '보낸 계정 (회원 또는 관리자)';
COMMENT ON COLUMN CHAT_MESSAGE.SENDER_TYPE_CODE IS 'USER=회원, ADMIN=관리자';
COMMENT ON COLUMN CHAT_MESSAGE.CONTENT IS '메시지 본문 (500자). 개인정보가 섞일 수 있어 로그에 남기지 않는다';
COMMENT ON COLUMN CHAT_MESSAGE.CREATED_AT IS '보낸 시각';
-- N-07 방 안의 메시지를 번호순으로 조회하기 위한 인덱스.
CREATE INDEX IX_CHM_ROOM ON CHAT_MESSAGE (ROOM_ID, MESSAGE_ID);

SELECT (SELECT COUNT(*) FROM CHAT_ROOM) AS EXPECTED_ZERO_ROOMS, (SELECT COUNT(*) FROM CHAT_MESSAGE) AS EXPECTED_ZERO_MESSAGES FROM DUAL;
