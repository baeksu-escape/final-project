-- 등급 구간 버전 CUT-0.3(DRAFT)와 구간 3행을 이미 만들어진 DB에 추가한다 (FP-139, 피처 정의서 10장 C27, decisions.md D-01).
-- 모델 0.2(LGBM-BASE-0.2)의 점수 분포로 다시 계산한 25/50/25 경계다: CAUTION 0부터 653, STANDARD 654부터 726, GOOD 727부터 1000
-- (기존 집단 VALID 1,800행의 대안 모델 점수 p25/p75 = 653/727). CUT-0.2(0.1 분포 기준 659/731)는 고치지 않는다. 최종 값은 FP-144(TEST) 이후 다시 계산한다.
-- 새로 DDL을 실행하는 DB는 avenue_ddl.sql 기준 데이터에 이미 들어 있으므로 이 파일이 필요 없다.
-- DRAFT라서 서비스는 바뀌지 않는다: ACTIVE는 계속 CUT-0.1(665·780)이고, CUT-0.3을 ACTIVE로 옮기는 일은 이 파일에 없다
-- (팀이 전환 시점을 정한 뒤 FastAPI 상수와 함께 따로 한다. ACTIVE는 동시에 1개만 허용된다).
-- 이미 같은 버전·구간이 있으면 넣지 않으므로 다시 실행해도 된다. CUT-0.1·CUT-0.2는 건드리지 않는다. 오류가 나면 두 단계가 함께 취소된다.
-- SQL*Plus/SQLcl/SQL Developer에서 대상 스키마 소유자로 실행한다. 공용 DB 실행은 DB 담당이 한다.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
WHENEVER OSERROR EXIT FAILURE ROLLBACK

MERGE INTO SCORE_CUTOFF_VERSION t
USING (SELECT 'CUT-0.3' AS CUTOFF_VERSION,
              'DRAFT' AS STATUS_CODE,
              '25/50/25 임시 결정 (D-01, 11/20). 모델 0.2 대안 모델 VALID 점수 p25/p75=653/727. 서비스 전환 시점 미정' AS NOTE
         FROM DUAL) s
   ON (t.CUTOFF_VERSION = s.CUTOFF_VERSION)
 WHEN NOT MATCHED THEN
      INSERT (CUTOFF_VERSION, STATUS_CODE, NOTE, ACTIVATED_AT)
      VALUES (s.CUTOFF_VERSION, s.STATUS_CODE, s.NOTE, NULL);

MERGE INTO SCORE_GRADE_BAND t
USING (SELECT 'CUT-0.3' AS CUTOFF_VERSION, 'CAUTION' AS GRADE_BAND_CODE, 0 AS MIN_SCORE, 653 AS MAX_SCORE, 1 AS DISPLAY_ORDER FROM DUAL
        UNION ALL
       SELECT 'CUT-0.3', 'STANDARD', 654, 726, 2 FROM DUAL
        UNION ALL
       SELECT 'CUT-0.3', 'GOOD', 727, 1000, 3 FROM DUAL) s
   ON (t.CUTOFF_VERSION = s.CUTOFF_VERSION AND t.GRADE_BAND_CODE = s.GRADE_BAND_CODE)
 WHEN NOT MATCHED THEN
      INSERT (CUTOFF_VERSION, GRADE_BAND_CODE, MIN_SCORE, MAX_SCORE, DISPLAY_ORDER)
      VALUES (s.CUTOFF_VERSION, s.GRADE_BAND_CODE, s.MIN_SCORE, s.MAX_SCORE, s.DISPLAY_ORDER);

COMMIT;

-- 확인: CUT-0.1 ACTIVE 1행(그대로), CUT-0.2 DRAFT, CUT-0.3 DRAFT 각 1행, 구간 9행(CUT-0.3은 653/654, 726/727 경계)이 나와야 한다.
SELECT CUTOFF_VERSION, STATUS_CODE FROM SCORE_CUTOFF_VERSION ORDER BY CUTOFF_VERSION;
SELECT CUTOFF_VERSION, GRADE_BAND_CODE, MIN_SCORE, MAX_SCORE FROM SCORE_GRADE_BAND ORDER BY CUTOFF_VERSION, DISPLAY_ORDER;
