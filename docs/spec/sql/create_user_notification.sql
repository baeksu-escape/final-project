-- D-23·D-25 기존 DB에 빈 알림 테이블만 추가한다. APP_USER가 있는 스키마에서 한 번 실행한다.
-- Oracle DDL은 자동 COMMIT된다. 기존 테이블이 있으면 오류로 중단하며 데이터는 추가하지 않는다.
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
-- D-23·D-25 공통 헤더 알림 저장용 빈 테이블. 알림 종류·생성·발송 규칙은 별도 구현한다.
CREATE TABLE USER_NOTIFICATION (
    NOTIFICATION_ID        NUMBER(19)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID                NUMBER(19)           NOT NULL,
    NOTIFICATION_TYPE_CODE VARCHAR2(50 CHAR)    NOT NULL,
    TITLE                  VARCHAR2(200 CHAR)   NOT NULL,
    CONTENT                VARCHAR2(1000 CHAR)  NOT NULL,
    LINK_URL               VARCHAR2(500 CHAR),
    READ_AT                TIMESTAMP,
    CREATED_AT             TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_NOTIFICATION PRIMARY KEY (NOTIFICATION_ID),
    CONSTRAINT FK_UNT_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID)
);
COMMENT ON TABLE USER_NOTIFICATION IS '회원별 헤더 알림. 빈 테이블만 준비하며 생성·발송 규칙은 별도 구현';
COMMENT ON COLUMN USER_NOTIFICATION.NOTIFICATION_ID IS '알림 번호';
COMMENT ON COLUMN USER_NOTIFICATION.USER_ID IS '알림 수신 회원';
COMMENT ON COLUMN USER_NOTIFICATION.NOTIFICATION_TYPE_CODE IS '알림 종류 코드. 허용 종류는 구현 시 확정';
COMMENT ON COLUMN USER_NOTIFICATION.TITLE IS '알림 제목. 개인정보 원문을 넣지 않는다';
COMMENT ON COLUMN USER_NOTIFICATION.CONTENT IS '알림 내용. 개인정보 원문을 넣지 않는다';
COMMENT ON COLUMN USER_NOTIFICATION.LINK_URL IS '서비스 내부 이동 경로. 외부 URL은 저장하지 않는다';
COMMENT ON COLUMN USER_NOTIFICATION.READ_AT IS '읽은 시각. NULL이면 안 읽음';
COMMENT ON COLUMN USER_NOTIFICATION.CREATED_AT IS '알림 생성 시각';
-- D-23 회원별 최신 알림 목록 조회를 위한 인덱스.
CREATE INDEX IX_UNT_USER_CREATED ON USER_NOTIFICATION (USER_ID, CREATED_AT);

SELECT COUNT(*) AS EXPECTED_ZERO_ROWS FROM USER_NOTIFICATION;
