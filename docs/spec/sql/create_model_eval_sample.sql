-- N-25 기존 DB에 모형 성능 비교용 평가 표본 표 MODEL_EVAL_SAMPLE만 추가한다 (DDL v0.3.2 C10, FP-235). 빈 표만 만들고 데이터는 넣지 않는다.
-- MODEL_REGISTRY와 DIM_WORKER_TYPE이 있는 스키마에서 한 번 실행한다. Oracle DDL은 자동 COMMIT된다. 같은 이름의 표가 이미 있으면 오류로 중단한다.
-- 표를 만든 뒤 load_model_eval_sample_lgbm_base_0_1.sql로 평가 표본을 적재한다. 공용 DB는 PR 작성자가 병합 후 실행하고 DB 변경 채널에 남긴다(sql README 「공용 DB 적용 규칙」).
-- 새로 DDL을 실행하는 DB(avenue_ddl.sql)에는 이미 들어 있으므로 실행하지 않는다.
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
-- v0.3.2 (C10) N-25 모형 성능 비교용 평가 표본. 평가 고객 1명이 1행이며 기존·대안 모델 점수와 정답 라벨 2개를 담는다.
-- 합성 학습 데이터로 낸 평가 결과라 서비스 회원의 평가(ASSESSMENT)와 별개다. 컷오프별 지표·ROC는 API가 이 표로 계산한다.
CREATE TABLE MODEL_EVAL_SAMPLE (
    EVAL_SAMPLE_ID            NUMBER(19)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    MODEL_VERSION             VARCHAR2(50 CHAR)    NOT NULL,
    SPLIT_CODE                VARCHAR2(10 CHAR)    NOT NULL,
    GROUP_CODE                VARCHAR2(10 CHAR)    NOT NULL,
    CUSTOMER_REF              VARCHAR2(30 CHAR)    NOT NULL,
    WORKER_TYPE_CODE          VARCHAR2(20 CHAR)    NOT NULL,
    LABEL_ANY_DELINQUENCY_12M NUMBER(1)            NOT NULL,
    LABEL_NONFIN_EFFECT_12M   NUMBER(1)            NOT NULL,
    SCORE_LEGACY_DELINQ       NUMBER(4)            NOT NULL,
    SCORE_ALT_DELINQ          NUMBER(4)            NOT NULL,
    SCORE_LEGACY_NONFIN       NUMBER(4)            NOT NULL,
    SCORE_ALT_NONFIN          NUMBER(4)            NOT NULL,
    CREATED_AT                TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MODEL_EVAL_SAMPLE PRIMARY KEY (EVAL_SAMPLE_ID),
    CONSTRAINT UK_MES_SAMPLE UNIQUE (MODEL_VERSION, SPLIT_CODE, GROUP_CODE, CUSTOMER_REF),
    CONSTRAINT FK_MES_MODEL FOREIGN KEY (MODEL_VERSION) REFERENCES MODEL_REGISTRY (MODEL_VERSION),
    CONSTRAINT FK_MES_WORKER_TYPE FOREIGN KEY (WORKER_TYPE_CODE) REFERENCES DIM_WORKER_TYPE (WORKER_TYPE_CODE),
    CONSTRAINT CK_MES_SPLIT CHECK (SPLIT_CODE IN ('TRAIN', 'VALID', 'TEST')),
    CONSTRAINT CK_MES_GROUP CHECK (GROUP_CODE IN ('LEGACY', 'THINFILE')),
    CONSTRAINT CK_MES_LABELS CHECK (LABEL_ANY_DELINQUENCY_12M IN (0, 1) AND LABEL_NONFIN_EFFECT_12M IN (0, 1)),
    CONSTRAINT CK_MES_SCORES CHECK (SCORE_LEGACY_DELINQ BETWEEN 0 AND 1000 AND SCORE_ALT_DELINQ BETWEEN 0 AND 1000
                                    AND SCORE_LEGACY_NONFIN BETWEEN 0 AND 1000 AND SCORE_ALT_NONFIN BETWEEN 0 AND 1000)
);
COMMENT ON TABLE  MODEL_EVAL_SAMPLE IS '모형 성능 비교(N-25)용 평가 표본. 합성 학습 데이터 고객별 기존·대안 모델 점수와 정답 라벨. 서비스 회원 평가(ASSESSMENT)와 별개이며 기본 시드에는 넣지 않고 load_model_eval_sample_*.sql로 적재한다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.EVAL_SAMPLE_ID IS '평가 표본 번호(자동 증가)';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.MODEL_VERSION IS '이 점수를 낸 모델 묶음 (MODEL_REGISTRY). 같은 버전으로 다시 적재하지 않고 새 MODEL_VERSION을 등록한다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.SPLIT_CODE IS 'TRAIN, VALID, TEST. 기존 집단은 VALID만, 씬파일은 모델이 학습하지 않아 TRAIN과 VALID를 쓴다. TEST는 최종 평가(FP-144) 때만 넣는다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.GROUP_CODE IS 'LEGACY=기존 집단, THINFILE=금융 이력 부족(씬파일) 집단. 씬파일은 기존 집단으로 학습한 모델을 적용한 결과다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.CUSTOMER_REF IS '합성 학습 데이터의 고객 번호(SYN…, THF…). 서비스 회원 번호가 아니다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.WORKER_TYPE_CODE IS '직군 (DIM_WORKER_TYPE). 직군별 오거절률 계산에 쓴다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.LABEL_ANY_DELINQUENCY_12M IS '정답 라벨: 12개월 안 연체 경험(1=불량). 연체 라벨에는 대안 데이터 효과를 넣지 않았다(데이터 생성 설계)';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.LABEL_NONFIN_EFFECT_12M IS '정답 라벨: 비금융 효과를 가정한 합성 라벨(1=불량). 설계로 넣은 효과가 반영돼 실제 개선의 근거가 아니다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.SCORE_LEGACY_DELINQ IS '연체 라벨로 학습·평가한 기존 모델 점수(0~1000, 높을수록 좋음). 서버에 올린 기존 모델(legacy.joblib)과 같다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.SCORE_ALT_DELINQ IS '연체 라벨로 학습·평가한 대안 모델 점수. 같은 라벨 비교용 실험 모델이라 서버 모델이 아니다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.SCORE_LEGACY_NONFIN IS '비금융 효과 라벨로 학습·평가한 기존 모델 점수. 같은 라벨 비교용 실험 모델이라 서버 모델이 아니다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.SCORE_ALT_NONFIN IS '비금융 효과 라벨로 학습·평가한 대안 모델 점수. 서버에 올린 대안 모델(alternative.joblib)과 같다';
COMMENT ON COLUMN MODEL_EVAL_SAMPLE.CREATED_AT IS '적재 시각';

